// 장소명과 소개글로 앱 카테고리를 고른다.
//
// 발굴 스크립트가 카테고리를 빈 배열로 넘기고 있었다(scripts/discover-places.mjs).
// 그래서 공공데이터로 등록한 56곳에 카테고리가 하나도 없었고, 그대로 공개했으면
// 카테고리 필터에도 안 걸리고 날씨 추천에서도 빠졌을 것이다 — 비 오는 날 실내를
// 앞으로 당기는 로직이 카테고리를 보고 판단하기 때문이다.
//
// 규칙은 지어내지 않고, 사람이 이미 카테고리를 붙여 둔 167곳에서 뽑았다.
// "수목원"이 든 8곳은 여덟 곳 모두 자연·공원이고, "박물관" 23곳 중 22곳이
// 체험·문화, 18곳이 실내놀이였다.

export const APP_CATEGORIES = [
  "무료", "영유아 무료입장", "자연·공원", "실내놀이", "맛집", "카페", "체험·문화", "스포츠",
];

// 야외라고 말하는 낱말. "자연"·"생태"는 여기 안 넣는다 — 땅끝해양자연사박물관,
// 부산기후변화체험교육관처럼 실내 시설 이름에도 그대로 들어간다.
const OUTDOOR = /수목원|식물원|공원|숲|해수욕장|해변|목장|정원|계곡|오름|둘레길|호수|저수지|농원|산림|캠핑|해안|폭포|농장|테마파크/;
const INDOOR = /박물관|과학관|미술관|아쿠아리움|수족관|전시관|체험관|체험장|천문대|도서관|키즈|실내|기념관|자료관|교육관|학습관|플라넷/;
const CULTURE = /박물관|과학관|미술관|전시관|체험관|체험장|천문대|기념관|자료관|교육관|학습관|테마파크|동물원|랜드|마을|문화|역사|유적|서원|향교|아쿠아리움|수족관|생태|목장|공방|미로|사과|막국수/;
const SPORTS = /자전거|스포츠|워터파크|워터플래닛|수영|스케이트|클라이밍|레포츠|썰매|빙상|체육|카트|짚라인|서핑/;

// "무료", "무료입장" 은 무료다. "어른 10,000원 / 36개월 미만 무료" 는 아니다 —
// 일부만 무료인 곳까지 무료로 묶으면 무료 필터가 거짓말이 된다.
const FREE = /^무료/;

/**
 * @param {object} place
 * @param {string} place.name 장소명
 * @param {string} [place.fee] 입장료 원문
 * @returns {string[]} 앱 카테고리. 하나도 못 정하면 빈 배열
 */
export function inferCategories({ name, fee = "" }) {
  const title = String(name || "");
  const cats = [];

  // 판단은 이름으로만 한다. 소개글에는 "근처에 공원이 있다" 같은 주변 설명이
  // 섞여 있어, 그것까지 보면 진안역사박물관이 자연·공원이 된다.
  const indoor = INDOOR.test(title);
  // 실내 시설 이름에 야외 낱말이 들어가도(국립산악박물관, 땅끝해양자연사박물관)
  // 야외로 보내지 않는다. 비 오는 날 추천에서 실내가 빠지는 게 더 나쁘다.
  if (OUTDOOR.test(title) && !indoor) cats.push("자연·공원");
  if (indoor) cats.push("실내놀이");
  if (CULTURE.test(title)) cats.push("체험·문화");
  if (SPORTS.test(title)) cats.push("스포츠");
  if (FREE.test(String(fee).trim())) cats.push("무료");

  return cats.filter((c, i) => cats.indexOf(c) === i && APP_CATEGORIES.includes(c));
}
